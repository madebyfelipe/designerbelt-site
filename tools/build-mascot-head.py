#!/usr/bin/env python3
"""Build the head-only mascot from the full body SVG.

The owner wants the hero character to be just the head, minimal, animated like a
small creature. Instead of redrawing it, this keeps the head subtree (ears, face,
muzzle, mouth, whiskers, eyes, squint, smile) and drops body, arms, belt, tail,
the floating tile and the check. Class names stay the same, so mascot.css keeps
working, and the viewBox is cropped to the head.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
src = (root / "mascot.svg").read_text(encoding="utf-8")

# the head subtree: <g class="dbm-head-look"> ... its matching close
start = src.index('<g class="dbm-head-look"')
depth, index = 0, start
while True:
    open_tag = src.find("<g", index)
    close_tag = src.find("</g>", index)
    if close_tag == -1:
        break
    if open_tag != -1 and open_tag < close_tag:
        depth += 1
        index = open_tag + 2
        continue
    depth -= 1
    index = close_tag + 4
    if depth == 0:
        break
head = src[start:index]

# the two eye clips live in <defs> and are referenced by the pupils
defs = re.search(r"<defs>.*?</defs>", src, re.S).group(0)

out = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="95 50 410 390" width="410" height="390" '
    'class="db-mascot" aria-hidden="true" focusable="false">\n'
    "<!-- Head-only mascot, generated by tools/build-mascot-head.py from mascot.svg. Do not edit by hand. -->\n"
    + defs
    + "\n"
    '<g class="dbm-root" id="dbm-root"><g class="dbm-torso" id="dbm-torso">'
    + head
    + "</g></g>\n</svg>\n"
)
(root / "mascot-head.svg").write_text(out, encoding="utf-8", newline="\n")
print("mascot-head.svg:", len(out), "bytes, head subtree", len(head), "bytes")
